#!/usr/bin/env python3
"""Check that every PMID in markers.js exists, and that each paper mentions the gene or rsID.

Needs internet (NCBI E-utilities).
Writes docs/REFERENCES.md, a human-readable list for reviewers.

Usage: python3 tools/verify_pmids.py
"""
import json, pathlib, sys, time, urllib.request, urllib.parse

ROOT = pathlib.Path(__file__).resolve().parent.parent
text = (ROOT / "markers.js").read_text(encoding="utf-8")
markers = json.loads(text[text.index("const MARKERS =") + 15:text.rindex("];") + 1])

pmids = sorted({p for m in markers for p in m["pmids"]})
EUTILS = "https://eutils.ncbi.nlm.nih.gov/entrez/eutils/"
UA = {"User-Agent": "dna-marker-explorer-ci"}

def get(url):
    with urllib.request.urlopen(urllib.request.Request(url, headers=UA), timeout=30) as r:
        return r.read().decode()

summ = {}
for i in range(0, len(pmids), 100):
    ids = ",".join(map(str, pmids[i:i + 100]))
    d = json.loads(get(EUTILS + "esummary.fcgi?db=pubmed&retmode=json&id=" + ids))["result"]
    for uid in d.get("uids", []):
        summ[int(uid)] = d[uid]
    time.sleep(0.4)

abstracts = {}
for p in pmids:  # abstracts, to check that the gene is mentioned
    try:
        abstracts[p] = get(EUTILS + "efetch.fcgi?db=pubmed&rettype=abstract&retmode=text&id=" + str(p)).lower()
    except Exception:
        abstracts[p] = ""
    time.sleep(0.35)

errors, warnings, lines = [], [], ["# References\n", "Generated by `tools/verify_pmids.py`. Do not edit by hand.\n"]
GUIDELINE_WORDS = ("cpic", "clinical pharmacogenetics implementation consortium", "guideline")
for m in markers:
    lines.append(f"\n## {m['gene']} · {m['id']}\n")
    for p in m["pmids"]:
        s = summ.get(p)
        if not s or "error" in s:
            errors.append(f"{m['id']}: PMID {p} not found"); continue
        title, year = s.get("title", ""), s.get("pubdate", "")[:4]
        author = s.get("sortfirstauthor", "")
        lines.append(f"- [{author} {year}. {title} *{s.get('source','')}*](https://pubmed.ncbi.nlm.nih.gov/{p}/)")
        hay = (title + " " + abstracts.get(p, "")).lower()
        genes = [g.strip().lower() for g in m["gene"].replace("/", " ").replace("(", " ").replace(")", " ").split()]
        if not any(len(g) > 2 and g in hay for g in genes) and m["id"] not in hay and not any(w in hay for w in GUIDELINE_WORDS):
            warnings.append(f"{m['id']} ({m['gene']}): PMID {p} doesn't mention the gene: '{title[:80]}'")

(ROOT / "docs" / "REFERENCES.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"{len(pmids)} PMIDs checked: {len(errors)} errors, {len(warnings)} warnings")
for w in warnings: print("  warn ", w)
for e in errors: print("  ERROR", e)
sys.exit(1 if errors else 0)
